// Copies the handful of Tabler icons the app uses into one module, so the
// window does not have to ship the whole icon set.
import { readFileSync, writeFileSync } from 'node:fs';

const names = [
  'download', 'history', 'bookmark', 'file-text', 'engine', 'settings', 'help', 'plus', 'player-pause', 'player-play',
  'x', 'refresh', 'folder', 'folder-open', 'trash', 'copy', 'search', 'chevron-down', 'chevron-right', 'check',
  'alert-triangle', 'alert-circle', 'clock', 'external-link', 'dots', 'link', 'music', 'movie', 'list', 'info-circle',
  'arrow-back-up', 'terminal-2', 'adjustments-horizontal', 'clipboard', 'calendar-time', 'file-import', 'file-export',
  'circle-check', 'circle-x', 'loader-2', 'eye', 'ban', 'playlist', 'pencil', 'lifebuoy', 'arrow-up', 'minus', 'cookie',
];
const out = {};
for (const n of names) {
  const svg = readFileSync(new URL(`../node_modules/@tabler/icons/icons/outline/${n}.svg`, import.meta.url), 'utf8');
  out[n] = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/<path stroke="none" d="M0 0h24v24H0z" fill="none"\s*\/>/, '').replace(/\s*\n\s*/g, '').trim();
}
writeFileSync(new URL('../src/renderer/icons.generated.ts', import.meta.url),
  `// Generated by scripts/gen-icons.mjs from @tabler/icons (MIT). Do not edit.\nexport const icons = ${JSON.stringify(out, null, 1)} as const;\nexport type IconName = keyof typeof icons;\n`);
console.log(`${names.length} icons written`);
